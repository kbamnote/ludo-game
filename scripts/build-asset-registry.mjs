/**
 * Copies the design-reference WebP assets into src/assets/images and
 * regenerates the typed registry that screens import from.
 *
 *   npm run build:assets
 *
 * Keeping this generated means the registry can never drift from what is
 * actually on disk, and adding a Stitch asset is a one-command operation.
 */
import { readdirSync, copyFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'design-reference/assets');
const DEST = join(ROOT, 'src/assets/images');

if (!existsSync(SRC)) {
  console.error(`  build-asset-registry: missing ${SRC}`);
  console.error(`  Fetch the design assets first:`);
  console.error(`    bash design-reference/assets/fetch-assets.sh`);
  process.exit(1);
}

mkdirSync(DEST, { recursive: true });

const assets = readdirSync(SRC)
  .filter((f) => f.endsWith('.webp'))
  .sort();

if (assets.length === 0) {
  console.error(`  build-asset-registry: no .webp files in ${SRC}`);
  process.exit(1);
}

let copied = 0;
for (const file of assets) {
  copyFileSync(join(SRC, file), join(DEST, file));
  copied += 1;
}

const toCamel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const entries = assets
  .map((f) => `  ${toCamel(f.replace('.webp', ''))}: require('./${f}'),`)
  .join('\n');

writeFileSync(
  join(DEST, 'index.js'),
  `/**
 * Asset registry — the single place a require() for an image may live.
 *
 * Screens import from here by name; no component ever holds a raw require().
 * That keeps paths in one place and makes it obvious which of the ${assets.length} Stitch
 * graphics are actually in use.
 *
 * GENERATED by scripts/build-asset-registry.mjs — run \`npm run build:assets\`.
 * Source: design-reference/assets/ (see design-reference/assets/manifest.tsv)
 */
export const images = {
${entries}
};

export default images;
`
);

console.log(`  build-asset-registry: ${copied} assets copied, ${assets.length} registry entries`);
